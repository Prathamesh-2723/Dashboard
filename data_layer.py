@st.cache_data
def get_shap_waterfall(window_id: str) -> Dict[str, Any]:
    """
    Returns additive SHAP contributions for a single 30s window.
    
    Real source when USE_MOCK = False:
        Calls shap.TreeExplainer(model).shap_values(window_feature_vector).
    """
    df = get_dataset()
    row_matches = df[df["window_id"] == window_id]
    if row_matches.empty:
        row = df.iloc[0]
    else:
        row = row_matches.iloc[0]

    pred_cls = row["predicted_class"]
    base_value = 0.333  # Uniform 3-class prior

    shap_values = {}
    if pred_cls == "BOT":
        shap_values["std_gap"] = 0.28          # Near zero gap strongly indicates bot
        shap_values["timing_entropy"] = 0.22   # Low entropy pushes to bot
        shap_values["concurrent_flows_max"] = 0.16 # Single connection
        shap_values["burstiness"] = -0.05
        shap_values["in_out_ratio"] = 0.11     # Small download ratio
        shap_values["mean_gap"] = 0.08
        shap_values["mean_flow_duration_ms"] = 0.06
        shap_values["unique_dst_ips"] = 0.04
        shap_values["pct_tls"] = 0.01
        shap_values["pct_small_flows"] = 0.03
    elif pred_cls == "AI-AGENT":
        shap_values["burstiness"] = 0.31       # High burstiness with thinking pauses
        shap_values["mean_gap"] = 0.21         # LLM thinking delays (4-9s)
        shap_values["concurrent_flows_max"] = 0.15 # 2-4 flows
        shap_values["timing_entropy"] = 0.10   # Semi-structured
        shap_values["std_gap"] = 0.09
        shap_values["in_out_ratio"] = 0.07
        shap_values["mean_flow_duration_ms"] = 0.04
        shap_values["unique_dst_ips"] = 0.02
        shap_values["pct_tls"] = 0.01
        shap_values["pct_small_flows"] = -0.02
    else:  # HUMAN
        shap_values["concurrent_flows_max"] = 0.26 # High parallel browsing
        shap_values["timing_entropy"] = 0.24       # Irregular human interaction
        shap_values["in_out_ratio"] = 0.19         # Heavy media/page download
        shap_values["std_gap"] = 0.12
        shap_values["unique_dst_ips"] = 0.09
        shap_values["mean_flow_duration_ms"] = 0.05
        shap_values["burstiness"] = -0.08
        shap_values["mean_gap"] = -0.04
        shap_values["pct_tls"] = 0.03
        shap_values["pct_small_flows"] = -0.03

    # Add realistic micro-noise to values
    np.random.seed(hash(window_id) % 2**32)
    adjusted_shaps = {}
    for feat, val in shap_values.items():
        adjusted_shaps[feat] = round(val + np.random.uniform(-0.02, 0.02), 4)

    total_shap = sum(adjusted_shaps.values())
    margin = round(base_value + total_shap, 3)

    return {
        "window_id": window_id,
        "predicted_class": pred_cls,
        "base_value": base_value,
        "features": adjusted_shaps,
        "raw_values": {feat: row.get(feat, 0) for feat in adjusted_shaps},
        "margin": margin
    }


