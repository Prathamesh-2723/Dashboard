@st.cache_data
def get_session_summaries(threshold: Optional[float] = None) -> pd.DataFrame:
    """
    Returns session-level aggregated records with dynamic uncertainty thresholding.
    
    Real source when USE_MOCK = False:
        Aggregates windowed predictions over sessions or reads model evaluation logs.
    """
    t = threshold if threshold is not None else get_uncertainty_threshold()
    df = get_dataset()
    sess_list = []

    for sess_id, grp in df.groupby("session_id"):
        true_cls = grp["class"].iloc[0]
        src_file = grp["source_file"].iloc[0]
        client_ip = grp["client_ip"].iloc[0]
        num_windows = len(grp)
        
        # Majority vote and average probabilities
        mean_p_human = grp["prob_human"].mean()
        mean_p_bot = grp["prob_bot"].mean()
        mean_p_agent = grp["prob_agent"].mean()

        probs = {"HUMAN": mean_p_human, "BOT": mean_p_bot, "AI-AGENT": mean_p_agent}
        top_cls = max(probs, key=probs.get)
        top_prob = probs[top_cls]

        uncertain_windows = grp["is_uncertain"].sum()
        sess_uncertain = (top_prob < t) or (uncertain_windows >= 2)

        sess_list.append({
            "session_id": sess_id,
            "source_file": src_file,
            "client_ip": client_ip,
            "true_class": true_cls,
            "predicted_class": top_cls,
            "prob_human": round(mean_p_human, 3),
            "prob_bot": round(mean_p_bot, 3),
            "prob_agent": round(mean_p_agent, 3),
            "confidence": round(top_prob, 3),
            "is_uncertain": sess_uncertain,
            "num_windows": num_windows,
            "total_bytes": grp["total_bytes"].sum(),
            "avg_concurrency": round(grp["concurrent_flows_max"].mean(), 1),
            "avg_entropy": round(grp["timing_entropy"].mean(), 2),
            "avg_burstiness": round(grp["burstiness"].mean(), 2),
        })

    return pd.DataFrame(sess_list)


