def format_ip(ip: str, role: Optional[str] = None) -> str:
    """
    Applies role-based privacy masking to IP addresses.
    - User (Analyst): Masked (e.g., '203.0.113.***') to meet SOC PII/GDPR privacy policies.
    - Admin: Full raw IP address for deep forensics.
    """
    curr_role = (role or st.session_state.get("user_role", "analyst")).lower()
    privacy_on = st.session_state.get("privacy_masking_enabled", True)
    
    if curr_role in ["analyst", "user"] and privacy_on:
        parts = ip.split(".")
        if len(parts) == 4:
            return f"{parts[0]}.{parts[1]}.{parts[2]}.***"
        return "***.***.***.***"
    return ip

