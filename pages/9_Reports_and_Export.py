def df_to_markdown_table(df) -> str:
    """Converts a DataFrame to a Markdown table using pure Python (no tabulate dependency)."""
    if df is None or getattr(df, "empty", True):
        return "_No counterfactual records available._"
    cols = [str(c) for c in df.columns]
    lines = [
        "| " + " | ".join(cols) + " |",
        "| " + " | ".join(["---"] * len(cols)) + " |"
    ]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join([str(val).replace("\n", " ").replace("|", "\\|") for val in row.values]) + " |")
    return "\n".join(lines)

